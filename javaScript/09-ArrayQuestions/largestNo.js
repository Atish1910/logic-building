// 2️⃣ Find the largest number in an array
console.log('Approch One : Without Inbuilt-----------------------------------------------------------------------------------');

const nums = [10, 45, 67, 23, 89];
iMax = -Infinity;
for(let i = 0; i < nums.length; i++){
    if(nums[i] > iMax){
        iMax = nums[i];
    }
}
console.log(iMax);

